# 别名/炮制品 → 药典正名（药典单列饮片项或性味项下仍标毒性）
ALIASES = {
    "法半夏": "半夏",   # 药典法半夏项下性味仍标"有毒"
    "紫箕贯众": "紫萁贯众",
}

# 原库英文分级 → 药典中文分级
EN2CN = {
    "extremely toxic": "大毒",
    "toxic": "有毒",
    "slightly toxic": "小毒",
}

GRADE_ORDER = {"大毒": 0, "有毒": 1, "小毒": 2}


def main():
    # 药典参考表
    with open(DATA / "yd2020_toxic83.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["yd_name", "grade", "dosage", "precaution"])
        for name, (g, d, p) in YD2020.items():
            w.writerow([name, g, d, p])

    with open(DATA / "TCMTox_herb.csv", encoding="utf-8-sig") as f:
        rows = list(csv.DictReader(f))

    stats = {"filled": [], "conflict": [], "consistent": [], "kept": [], "still_empty": []}
    out = []
    for r in rows:
        name = r["Herb_cn_name"].strip()
        orig = (r["Toxicity"] or "").strip()
        orig_cn = EN2CN.get(orig.lower(), "")  # 大小写归一后映射
        yd_name = name if name in YD2020 else ALIASES.get(name)
        yd_grade = YD2020[yd_name][0] if yd_name else ""

        if yd_grade and orig_cn:
            if yd_grade == orig_cn:
                final, src, conflict = yd_grade, "药典2020+库标注一致", ""
                stats["consistent"].append(name)
            else:
                final, src, conflict = yd_grade, f"药典2020(以药典为准,原标{orig})", f"{orig_cn}≠{yd_grade}"
                stats["conflict"].append((name, orig_cn, yd_grade))
        elif yd_grade:
            final, src, conflict = yd_grade, "药典2020补齐", ""
            stats["filled"].append((name, yd_grade))
        elif orig_cn:
            final, src, conflict = orig_cn, f"TCMToxDB原标({orig})", ""
            stats["kept"].append(name)
        else:
            final, src, conflict = "", "无来源", ""
            stats["still_empty"].append(name)

        r["Toxicity_original"] = orig
        r["Toxicity_grade"] = final            # 统一中文分级: 大毒/有毒/小毒/空
        r["Toxicity_source"] = src
        r["Toxicity_conflict"] = conflict
        out.append(r)

    fields = list(out[0].keys())
    with open(DATA / "TCMTox_herb_clean.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        w.writerows(out)

    # ---- 报告 ----
    n = len(out)
    labeled = [r for r in out if r["Toxicity_grade"]]
    print(f"总计 {n} 味 | 清洗后有分级: {len(labeled)} (原来 43)")
    from collections import Counter
    print("分级分布:", dict(Counter(r["Toxicity_grade"] for r in labeled if r["Toxicity_grade"])))
    print(f"\n[1] 药典补齐空标注 {len(stats['filled'])} 味:")
    print("   ", "、".join(f"{a}({b})" for a, b in stats["filled"]))
    print(f"\n[2] 原标注与药典冲突 {len(stats['conflict'])} 味 (已按药典修正, 原值保留在 Toxicity_original):")
    for a, o, y in stats["conflict"]:
        print(f"    {a}: 原标{o} → 药典{y}")
    print(f"\n[3] 一致 {len(stats['consistent'])} 味 | 仅库标注(药典无) {len(stats['kept'])} 味:")
    print("   ", "、".join(stats["kept"]))
    print(f"\n[4] 仍无分级 {len(stats['still_empty'])} 味 (药典83种未收载, 不臆造)")
    notable = {"关木通", "广防己", "青木香", "雷公藤", "雪上一枝蒿", "鸦胆子", "见血封喉", "相思子", "鸦片"}
    hits = [x for x in stats["still_empty"] if x in notable]
    print("    其中已知高关注品种(文献常标大毒/已除名): ", "、".join(hits) if hits else "-")


if __name__ == "__main__":
    main()
